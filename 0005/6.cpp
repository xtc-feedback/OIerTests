#include <bits/stdc++.h>
using namespace std;
int n, a[101][101];
int main()
{
    cin >> n;
    for (int i = 1; i <= n; i++)
        a[0][i] = 1, a[n + 1][i] = 1, a[i][0] = 1, a[i][n + 1] = 1;
    int x = 1, y = 1, p = 1;
    while (p <= n * n)
    {
        while (a[x][y] == 0) a[x][y++] = p++;
        y--, x++;
        while (a[x][y] == 0) a[x++][y] = p++;
        x--, y--;
        while (a[x][y] == 0) a[x][y--] = p++;
        y++, x--;
        while (a[x][y] == 0) a[x--][y] = p++;
        x++, y++;
    }
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= n; j++)
            cout << a[i][j] << " ";
        cout << endl;
    }
}
// 这个代码的原理详解：
// 1. 首先读取矩阵的大小n，并初始化一个(n+2)x(n+2)的二维数组a，将边界元素设为1，内部元素设为0。
// 2. 使用变量x和y表示当前填充的位置，初始位置为(1,1)，变量p表示当前要填充的数字，初始值为1。
// 3. 使用一个while循环，直到p大于n*n，表示所有数字都已填充完毕。
// 4. 在每个循环中，按照顺时针方向依次填充数字：
//    - 向右填充：当当前位置a[x][y]为0时，填充数字p，并将y加1，直到遇到非0元素。
//    - 向下填充：调整位置后，继续向下填充数字
//    - 向左填充：调整位置后，继续向左填充数字
//    - 向上填充：调整位置后，继续向上填充数字
// 5. 每次填充完一个方向后，调整x和y的位置，以便开始下一个方向的填充。
// 6. 最后，使用嵌套循环输出填充后的n x n矩阵。
// 比喻一下，这个过程就像是在一个有围墙的花园里种花，围墙防止你走出边界。你从花园的左上角开始，顺时针方向依次种花，直到整个花园都种满了花，然后把花园展示出来。