/*
题目描述
输入一个n行n列的整型矩阵，将对角线上的数加上10，再输出该矩阵，输出每个数字占5列(printf("%5d", );)，右对齐。 （n<=100，数组的元素不会超过4位数）
输入格式
第一行输入一个整数n

接下来输入一个n*n的矩阵。

输出格式
输出结果举证。
*/
#include <bits/stdc++.h>
using namespace std;
int n, a[101][101];
int main()
{
    cin >> n;
    for (int i = 1; i <= n; i++)
        for (int j = 1; j <= n; j++)
            cin >> a[i][j];
    int x = 1, y = 1;
    for (int i = 1; i <= n; i++)
    {
        a[x][y] += 10;
        x++;
        y++;
    }
    x = 1, y = n;
    for (int i = 1; i <= n; i++)
    {
        a[x][y] += 10;
        x++;
        y--;
    }
    if (n % 2 == 1) a[(n + 1) / 2][(n + 1) / 2] -= 10;
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= n; j++)
            printf("%5d", a[i][j]);
        cout << endl;
    }
    
}
// 这个代码的原理详解：
// 1. 首先读取矩阵的大小n和矩阵元素，并存储在二维数组a中。
// 2. 然后通过两个循环分别处理主对角线和副对
// 3. 对于主对角线，使用变量x和y从(1,1)开始，每次循环将a[x][y]加10，然后x和y都加1，直到处理完所有对角线元素。
// 4. 对于副对角线，重新初始化x为1，y为
// n，从(1,n)开始，每次循环将a[x][y]加10，然后x加1，y减1，直到处理完所有对角线元素。
// 5. 如果n是奇数，说明主对角线和副对角线在中心元素处重合，因此需要将该元素减去10以避免重复加10。
// 6. 最后，使用嵌套循环输出修改后的矩阵，确保每个数字占5列且右对齐。
// 比喻一下，这个过程就像是在一个棋盘上给两条对角线上的棋子都涂上颜色，如果棋盘大小是奇数，那么中间的那个棋子会被涂两次，所以需要把它的颜色去掉一次，最后把整个棋盘展示出来。